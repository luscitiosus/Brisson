def check(urn):
    s=''.join(T[c] for c in urn.lower())
    tot=sum((i+1)*int(d) for i,d in enumerate(s))
    return (tot//int(s[-1]))%10
def url_p(n,vol='735303'):
    u=f'urn:nbn:de:gbv:3:1-{vol}-p{n:04d}-'
    return u+str(check(u))
